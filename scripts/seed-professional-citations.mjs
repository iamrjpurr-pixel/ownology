async function main() {
  const dbUrl = process.env.DATABASE_URL;
  if (!dbUrl) { console.error("DATABASE_URL not set"); process.exit(1); }
  const conn = await mysql.createConnection(dbUrl);

  // Ensure the table exists (defensive — the server bootstrap creates it,
  // but this script can be run before the server has started).
  await conn.execute(`
    CREATE TABLE IF NOT EXISTS professional_citations (
      id INT PRIMARY KEY AUTO_INCREMENT,
      source_key VARCHAR(64) NOT NULL,
      authors VARCHAR(256) NOT NULL,
      title VARCHAR(256) NOT NULL,
      edition VARCHAR(64),
      chapter_ref VARCHAR(32),
      section_ref VARCHAR(64),
      page_range VARCHAR(32),
      section_title VARCHAR(256) NOT NULL,
      subject_summary TEXT NOT NULL,
      topic_tags VARCHAR(512) NOT NULL,
      wbs_domain VARCHAR(10),
      wbs_code VARCHAR(10),
      priority INT NOT NULL DEFAULT 50,
      created_at BIGINT NOT NULL,
      INDEX pc_source_key_idx (source_key),
      INDEX pc_wbs_code_idx (wbs_code),
      INDEX pc_priority_idx (priority)
    )
  `);

  // Idempotent: wipe & reseed.
  const [del] = await conn.execute("DELETE FROM professional_citations");
  console.log(`[Seed] Cleared ${del.affectedRows} existing citations`);

  let inserted = 0;
  for (const c of CITATIONS) {
    await conn.execute(
      `INSERT INTO professional_citations
        (source_key, authors, title, edition, chapter_ref, section_ref, page_range,
         section_title, subject_summary, topic_tags, wbs_domain, wbs_code, priority, created_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        c.sourceKey,
        c.authors,
        c.title,
        c.edition ?? null,
        c.chapterRef ?? null,
        c.sectionRef ?? null,
        c.pageRange ?? null,
        c.sectionTitle,
        c.subjectSummary,
        c.topicTags,
        c.wbsDomain ?? null,
        c.wbsCode ?? null,
        c.priority ?? 50,
        Date.now(),
      ]
    );
    inserted++;
  }
  console.log(`[Seed] Inserted ${inserted} professional citations across ${new Set(CITATIONS.map((c) => c.sourceKey)).size} sources`);
  await conn.end();
}

main().catch((e) => { console.error(e); process.exit(1); });
